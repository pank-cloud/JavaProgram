package assignments;

public class Assignment11 {

	public static void main(String[] args) {

		//WAP to print from 10 to 40
		
		for(int i = 10; i<=40; i++)
		{
			System.out.println(i);
		}		
	
		System.out.println();
		
		//WAP to print from -10 to -40
		
		for(int i=-10 ; i>=-40 ; i--)
		{
			System.out.println(i);
		}
		
		System.out.println();

		//WAP to print from -10 to 10		
		
		for(int i = -10; i<= 10; i++)
		{
			System.out.println(i);
		}
	
	}

}
